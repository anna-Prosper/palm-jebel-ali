#!/usr/bin/env node
// Deterministic generator for lib/content/i18n/registry.ts.
// Scans lib/content/i18n/{ar,ru}/*.ts, reads each file's export name + meta.slug,
// buckets by slug prefix, and rewrites the i18n registry. Run after adding
// translation files: `node scripts/gen-i18n-registry.mjs`.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const I18N = join(ROOT, "lib", "content", "i18n");
const LOCALES = ["ar", "ru"];

const bucketFor = (slug) =>
  slug.startsWith("communities/") ? "COMMUNITIES"
  : slug.startsWith("residences/") ? "RESIDENCES"
  : slug.startsWith("buy-property-in/") ? "BUY"
  : slug.startsWith("rent-property-in/") ? "RENT"
  : slug.startsWith("off-plan-in/") ? "OFFPLAN"
  : "GUIDES";

const isHub = (b) => b !== "GUIDES";

const entries = []; // { locale, file, name, slug, key, bucket }
for (const locale of LOCALES) {
  const dir = join(I18N, locale);
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".ts")).sort()) {
    const src = readFileSync(join(dir, f), "utf8");
    const nameM = src.match(/export const (\w+)\s*[:=]/);
    const slugM = src.match(/slug:\s*["'`]([^"'`]+)["'`]/);
    if (!nameM || !slugM) { console.warn(`  ! skipped ${locale}/${f}`); continue; }
    const slug = slugM[1];
    entries.push({ locale, file: f.replace(/\.ts$/, ""), name: nameM[1], slug, key: slug.split("/").pop(), bucket: bucketFor(slug) });
  }
}

const imports = entries.map((e) => `import { ${e.name} } from "@/lib/content/i18n/${e.locale}/${e.file}";`).join("\n");

// bucket -> key -> { ar, ru }
const maps = {};
for (const e of entries) {
  (maps[e.bucket] ??= {});
  (maps[e.bucket][e.key] ??= {});
  maps[e.bucket][e.key][e.locale] = e.name;
}

function renderMap(bucket) {
  const m = maps[bucket] || {};
  const type = isHub(bucket) ? "HubContent" : "GuideContent";
  const body = Object.entries(m)
    .map(([key, byLoc]) => {
      const inner = LOCALES.filter((l) => byLoc[l]).map((l) => `${l}: ${byLoc[l]}`).join(", ");
      return `  ${JSON.stringify(key)}: { ${inner} },`;
    })
    .join("\n");
  return `export const I18N_${bucket}: Record<string, Partial<Record<Locale, ${type}>>> = {${body ? "\n" + body + "\n" : ""}};`;
}

const out = `// AUTO-GENERATED by scripts/gen-i18n-registry.mjs — do not edit by hand.
import type { HubContent, GuideContent } from "@/lib/content/types";
import type { Locale } from "@/lib/i18n";
${imports}

${renderMap("COMMUNITIES")}
${renderMap("RESIDENCES")}
${renderMap("BUY")}
${renderMap("RENT")}
${renderMap("OFFPLAN")}
${renderMap("GUIDES")}

const ALL_MAPS = [I18N_COMMUNITIES, I18N_RESIDENCES, I18N_BUY, I18N_RENT, I18N_OFFPLAN, I18N_GUIDES];

// Which non-English locales exist for a given base slug (any type).
export function translatedLocales(slug: string): Locale[] {
  const c = ALL_MAPS.map((m) => m[slug]).find(Boolean);
  const out: Locale[] = [];
  if (c?.ar) out.push("ar");
  if (c?.ru) out.push("ru");
  return out;
}
`;

writeFileSync(join(I18N, "registry.ts"), out);
const counts = Object.fromEntries(Object.keys(maps).map((b) => [b, Object.keys(maps[b]).length]));
console.log(`i18n registry written — ${entries.length} translation files.`, counts);
