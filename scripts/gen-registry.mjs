#!/usr/bin/env node
// Deterministic registry generator for the Palm Jebel Ali content cluster.
// Scans lib/content/** for content files and (re)writes lib/content/registry.ts.
// This removes the one fragile manual step from the page-factory pipeline —
// new content files are wired automatically, no hand-edited imports.
//
// Bucketing:
//   communities/*  -> COMMUNITIES        residences/*  -> RESIDENCES
//   intent/buy-*   -> INTENT_BUY         intent/rent-* -> INTENT_RENT
//   intent/offplan-* -> INTENT_OFFPLAN   guides/*      -> GUIDES
// Map key = last path segment of each file's `meta.slug`.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = join(ROOT, "lib", "content");

// Flagship guides pinned to the top of the index; everything else follows,
// ordered by filename.
const GUIDE_PRIORITY = [
  "palm-jebel-ali-investor-guide",
  "palm-jebel-ali-prices",
  "palm-jebel-ali-payment-plans",
  "palm-jebel-ali-villas",
  "palm-jebel-ali-vs-palm-jumeirah",
];

function scan(dir) {
  const out = [];
  for (const f of readdirSync(join(CONTENT, dir)).filter((f) => f.endsWith(".ts")).sort()) {
    const src = readFileSync(join(CONTENT, dir, f), "utf8");
    const nameM = src.match(/export const (\w+)\s*[:=]/);
    const slugM = src.match(/slug:\s*["'`]([^"'`]+)["'`]/);
    if (!nameM || !slugM) {
      console.warn(`  ! skipped ${dir}/${f} (no export const / slug found)`);
      continue;
    }
    const base = f.replace(/\.ts$/, "");
    out.push({ dir, file: base, name: nameM[1], slug: slugM[1], key: slugM[1].split("/").pop() });
  }
  return out;
}

const communities = scan("communities");
const residences = scan("residences");
const intent = scan("intent");
const guides = scan("guides");

const buy = intent.filter((e) => e.file.startsWith("buy-"));
const rent = intent.filter((e) => e.file.startsWith("rent-"));
const offplan = intent.filter((e) => e.file.startsWith("offplan-"));

// Order guides: priority list first, then the rest alphabetically by key.
const gPinned = GUIDE_PRIORITY.map((k) => guides.find((g) => g.key === k)).filter(Boolean);
const gRest = guides.filter((g) => !GUIDE_PRIORITY.includes(g.key)).sort((a, b) => a.key.localeCompare(b.key));
const guidesOrdered = [...gPinned, ...gRest];

const all = [...communities, ...residences, ...buy, ...rent, ...offplan, ...guidesOrdered];

const imports = all.map((e) => `import { ${e.name} } from "@/lib/content/${e.dir}/${e.file}";`).join("\n");

const mapLit = (entries) =>
  entries.length
    ? `{\n${entries.map((e) => `  ${JSON.stringify(e.key)}: ${e.name},`).join("\n")}\n}`
    : "{}";

const out = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit by hand.
// Run \`node scripts/gen-registry.mjs\` after adding content files.
import type { HubContent, GuideContent } from "@/lib/content/types";
${imports}

export const COMMUNITIES: Record<string, HubContent> = ${mapLit(communities)};
export const RESIDENCES: Record<string, HubContent> = ${mapLit(residences)};
export const INTENT_BUY: Record<string, HubContent> = ${mapLit(buy)};
export const INTENT_RENT: Record<string, HubContent> = ${mapLit(rent)};
export const INTENT_OFFPLAN: Record<string, HubContent> = ${mapLit(offplan)};
export const GUIDES: Record<string, GuideContent> = ${mapLit(guidesOrdered)};

export const GUIDE_SLUGS = Object.keys(GUIDES);
`;

writeFileSync(join(CONTENT, "registry.ts"), out);
console.log(
  `registry.ts written — ${communities.length} communities, ${residences.length} residences, ` +
    `${buy.length} buy, ${rent.length} rent, ${offplan.length} off-plan, ${guides.length} guides ` +
    `(${all.length} total).`,
);
